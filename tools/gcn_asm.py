"""Assemble a GCN (gfx7) shader with llvm-mc into a C header: gcn_asm.py <in.s> <out.h> <name>.

The header holds the code as `static const u32 <name>[]` plus <NAME>_VGPRS and <NAME>_SGPRS,
the register counts COMPUTE_PGM_RSRC1 needs (highest register used + 1; SGPRs include VCC).
"""
import os, re, subprocess, sys

MC = os.environ.get("LLVM_MC") or "/opt/homebrew/opt/llvm/bin/llvm-mc"


def main(src, dst, name):
    r = subprocess.run([MC, "-triple=amdgcn", "-mcpu=gfx700", "-show-encoding", src],
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(r.stderr)
    code = bytearray()
    vgprs = sgprs = 0
    for line in r.stdout.splitlines():
        m = re.search(r"encoding: \[([^\]]*)\]", line)
        if not m:
            continue
        if re.search(r"[^0-9a-fx, ]", m.group(1)):
            # a fixup llvm-mc leaves unresolved here (a branch's offset shows as A,A): its bytes
            # would be taken for hex (A = 0x0a) and the branch would jump anywhere
            sys.exit("unresolved fixup (a branch?) in: " + line.strip())
        code += bytes(int(b, 16) for b in m.group(1).split(","))
        text = line.split(";")[0]
        for lo, hi in re.findall(r"\bv\[(\d+):(\d+)\]", text):
            vgprs = max(vgprs, int(hi) + 1)
        for v in re.findall(r"\bv(\d+)\b", text):
            vgprs = max(vgprs, int(v) + 1)
        for lo, hi in re.findall(r"\bs\[(\d+):(\d+)\]", text):
            sgprs = max(sgprs, int(hi) + 1)
        for s in re.findall(r"\bs(\d+)\b", text):
            sgprs = max(sgprs, int(s) + 1)
    words = [int.from_bytes(code[i:i + 4], "little") for i in range(0, len(code), 4)]
    out = ["/* generated by tools/gcn_asm.py from %s - do not edit */" % os.path.basename(src),
           "#pragma once",
           "#define %s_VGPRS %d" % (name.upper(), vgprs),
           "#define %s_SGPRS %d /* + VCC */" % (name.upper(), sgprs + 2),
           "static const u32 %s[%d] = {" % (name, len(words))]
    for i in range(0, len(words), 6):
        out.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 6]) + ",")
    out.append("};")
    open(dst, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:4])
