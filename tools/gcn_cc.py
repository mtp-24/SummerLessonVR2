"""Compile a GCN (gfx7) compute shader written in C into a C header: gcn_cc.py <in.c> <out.h> <name>.

The C file's one remaining function, `filter_main(const K *k, int gx, int gy, int tx, int ty)`
(another name in GCN_ENTRY), becomes an amdgpu_cs entry: the constants' address in s[0:1] and the
group's x and y in s2 and s3 (inreg), the thread's x and y in v0 and v1, as COMPUTE_PGM_RSRC2 with
2 user SGPRs, TGID x and y and TIDIG 1 sets them up. Everything else must be inlined, and the code
may not use scratch memory, calls or constant data of its own.

The header holds the code as `static const u32 <name>[]` plus <NAME>_VGPRS and <NAME>_SGPRS,
as tools/gcn_asm.py writes them.
"""
import os, re, subprocess, sys, tempfile

LLVM = os.environ.get("LLVM") or "/opt/homebrew/opt/llvm/bin"
TARGET = ["-mtriple=amdgcn-amd-amdpal", "-mcpu=gfx701"]
ENTRY = os.environ.get("GCN_ENTRY", "filter_main")


def run(*cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(" ".join(cmd) + "\n" + r.stderr)
    return r.stdout


def main(src, dst, name):
    with tempfile.TemporaryDirectory() as d:
        ll, cs, s, o, b = (os.path.join(d, n) for n in ("a.ll", "cs.ll", "a.s", "a.o", "a.bin"))
        run(LLVM + "/clang", "-target", "amdgcn-amd-amdpal", "-mcpu=gfx701", "-O2", "-nogpulib",
            "-ffast-math", "-S", "-emit-llvm", "-o", ll, src)
        ir = open(ll).read()
        # the entry: the amdgpu_cs calling convention, constants and group in SGPRs
        pat = (r"^define (?:hidden |dso_local )*void @%s\(ptr addrspace\(4\) ([^%%]*)%%0, "
               r"i32 noundef %%1, i32 noundef %%2," % ENTRY)
        ir, n = re.subn(pat, r"define amdgpu_cs void @%s(ptr addrspace(4) inreg \1%%0, "
                        r"i32 inreg noundef %%1, i32 inreg noundef %%2," % ENTRY, ir, flags=re.M)
        if n != 1:
            sys.exit("%s: no entry %s(const K *, int, int, int, int)" % (src, ENTRY))
        if len(re.findall(r"^define ", ir, flags=re.M)) != 1:
            sys.exit("%s: functions left that weren't inlined" % src)
        open(cs, "w").write(ir)
        run(LLVM + "/llc", *TARGET, "-O2", cs, "-o", s)
        asm = open(s).read()
        m = re.search(r"^\s+(s_getpc|s_swappc|scratch_|buffer_|flat_)\w*", asm, flags=re.M)
        if m:
            sys.exit("%s: the code uses %s (constant data, calls or scratch)" % (src, m.group(1)))
        if not re.search(r"; ScratchSize: 0\b", asm):
            sys.exit("%s: the code needs scratch memory" % src)
        vgprs = int(re.search(r"; NumVgprs: (\d+)", asm).group(1))
        sgprs = int(re.search(r"; TotalNumSgprs: (\d+)", asm).group(1))
        run(LLVM + "/llc", *TARGET, "-O2", "-filetype=obj", cs, "-o", o)
        run(LLVM + "/llvm-objcopy", "-O", "binary", "--only-section=.text", o, b)
        code = open(b, "rb").read()
    code += b"\0" * (-len(code) % 4)
    words = [int.from_bytes(code[i:i + 4], "little") for i in range(0, len(code), 4)]
    out = ["/* generated by tools/gcn_cc.py from %s - do not edit */" % os.path.basename(src),
           "#pragma once",
           "#define %s_VGPRS %d" % (name.upper(), vgprs),
           "#define %s_SGPRS %d /* with VCC */" % (name.upper(), sgprs),
           "static const u32 %s[%d] = {" % (name, len(words))]
    for i in range(0, len(words), 6):
        out.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 6]) + ",")
    out.append("};")
    open(dst, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:4])
