"""Generate agent/nids_gen.h from agent/imports.def and agent/hooks.def.

imports.def lines: <module basename> <symbol>[=<NID>] (functions the agent calls)
hooks.def lines:   <symbol>[=<NID>]                 (game imports the agent replaces)
For each, the NID (base64 of the reversed first 8 bytes of sha1(name+salt)).
"""
import base64, hashlib, os, sys

SALT = bytes.fromhex("518D64A635DED8C1E6B039B1C3E55230")


def nid(name):
    h = hashlib.sha1(name.encode() + SALT).digest()[:8][::-1]
    return base64.b64encode(h).decode().replace("/", "-").rstrip("=")


def main(agent_dir):
    out = ["/* generated by tools/gen_nids.py - do not edit */", "#pragma once"]
    for line in open(os.path.join(agent_dir, "imports.def")):
        line = line.split("#")[0].strip()
        if not line:
            continue
        mod, sym = line.split()
        sym, _, given = sym.partition("=")
        out.append('#define NID_%s "%s"' % (sym, given or nid(sym)))
        out.append('#define MOD_%s "%s"' % (sym, mod))
    for line in open(os.path.join(agent_dir, "hooks.def")):
        line = line.split("#")[0].strip()
        if not line:
            continue
        name, _, given = line.partition("=")
        out.append('#define HNID_%s "%s"' % (name, given or nid(name)))
    open(os.path.join(agent_dir, "nids_gen.h"), "w").write("\n".join(out) + "\n")
    hooks = []
    for line in open(os.path.join(agent_dir, "hooks.def")):
        line = line.split("#")[0].strip()
        if line:
            hooks.append("H(%s)" % line.partition("=")[0])
    open(os.path.join(agent_dir, "hooks.inc"), "w").write(
        "/* generated by tools/gen_nids.py from hooks.def */\n" + "\n".join(hooks) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "../agent"))
